package com.wire.android.util.ui

import androidx.compose.ui.input.key.Key
import androidx.compose.ui.input.key.KeyEvent
import androidx.compose.ui.input.key.KeyEventType
import androidx.compose.ui.input.key.isAltPressed
import androidx.compose.ui.input.key.isCtrlPressed
import androidx.compose.ui.input.key.isMetaPressed
import androidx.compose.ui.input.key.isShiftPressed
import androidx.compose.ui.input.key.key
import androidx.compose.ui.input.key.type

internal fun KeyEvent.isContextMenuShortcut(): Boolean =
    !isAltPressed && !isCtrlPressed && !isMetaPressed &&
        ((key == Key.Menu && !isShiftPressed) || (key == Key.F10 && isShiftPressed))

internal fun KeyEvent.handleContextMenuShortcut(onOpen: () -> Unit): Boolean {
    if (!isContextMenuShortcut()) return false
    if (type == KeyEventType.KeyDown && nativeKeyEvent.repeatCount == 0) onOpen()
    return true
}
